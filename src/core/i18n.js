export const currentLocale = () => locale;
export function translate(message) {
  if (locale !== "en") return message;
  if (Object.hasOwn(english, message)) return english[message];
  if (message.includes(" · ")) return message.split(" · ").map(translate).join(" · ");
  const duration = message.match(/^(最近 )?(\d+) (分钟|小时|天)$/);
  if (duration) return `${duration[1] ? "Last " : ""}${duration[2]} ${{ 分钟: "min", 小时: "h", 天: "days" }[duration[3]]}`;
  const count = message.match(/^(\d+) \/ (\d+) 次答案匹配$/);
  if (count) return `${count[1]} / ${count[2]} answers matched`;
  const namedCount = message.match(/^(总请求|失败|输入|输出) (\d+)$/);
  if (namedCount) return `${{ 总请求: "Total requests", 失败: "Errors", 输入: "Input", 输出: "Output" }[namedCount[1]]} ${namedCount[2]}`;
  const history = message.match(/^(.*)历史$/);
  if (history && english[history[1]]) return `${english[history[1]]} history`;
  return message;
}
let observer;
const originals = new WeakMap();
const skipped = "script,style,pre,code,textarea,.question-prompt,.question-result,.question-result dd,[translate=no]";

export function resolveLocale(value, languages = globalThis.modivueLanguages || navigator.languages || [navigator.language]) {
  if (value === "en" || value === "zh-CN") return value;
  const language = languages.find(language => /^(zh|en)(-|$)/i.test(language)) || languages[0] || "en";
  return /^zh(-|$)/i.test(language) ? "zh-CN" : "en";
}

export function setLocale(value) {
  locale = resolveLocale(value);
  document.documentElement.lang = locale;
  if (!observer) {
    observer = new MutationObserver(localize);
    observer.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ["title", "placeholder", "aria-label"] });
  }
  localize();
}

// Translate existing text nodes without replacing controls or changing values.
function localize() {
  if (!document.body) return;
  observer?.disconnect();
  const visit = (node, attribute) => {
    const value = attribute ? node.getAttribute(attribute) : node.nodeValue;
    if (!value?.trim()) return;
    let record = originals.get(node);
    if (!record) { record = {}; originals.set(node, record); }
    const key = attribute || "text";
    const source = record[key]?.translated === value ? record[key].source : value;
    const trimmed = source.trim();
    const translated = source.replace(trimmed, translate(trimmed));
    record[key] = { source, translated };
    if (value !== translated) { if (attribute) node.setAttribute(attribute, translated); else node.nodeValue = translated; }
  };
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) if (!walker.currentNode.parentElement?.closest(skipped)) visit(walker.currentNode);
  for (const element of document.querySelectorAll("[title],[placeholder],[aria-label]")) {
    if (!element.closest(skipped)) for (const name of ["title", "placeholder", "aria-label"]) if (element.hasAttribute(name)) visit(element, name);
  }
  observer?.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ["title", "placeholder", "aria-label"] });
}
